#!/usr/bin/env python3
"""Generate backlog/SHORTS_LINKS.md — the running list of download links for every
rendered philosophy short. Scans successful `shorts.yml` GitHub Actions runs, maps
each to its code via the short-<CODE> artifact name, and writes a markdown table.
Thinker / title come from each shorts/<CODE>.json.

Usage:  python tools/gen_shorts_links.py
Requires: gh CLI authenticated for this repo.
"""
import json
import subprocess
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Already uploaded to YouTube — exclude from the download doc so only new,
# not-yet-posted shorts remain. Add a code here once its short is published.
POSTED = {"CA-01", "KA-01", "NI-01", "ST-01", "ST-02", "ST-03", "ST-04"}


def gh_json(args):
    out = subprocess.run(["gh", *args], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit(f"gh failed: {' '.join(args)}\n{out.stderr}")
    return json.loads(out.stdout) if out.stdout.strip() else []


def gh_lines(args):
    import time
    for attempt in range(4):
        out = subprocess.run(["gh", *args], capture_output=True, text=True)
        if out.returncode == 0:
            return [ln for ln in out.stdout.splitlines() if ln.strip()]
        time.sleep(1.5 * (attempt + 1))
    return []


def meta_for(code):
    p = ROOT / "shorts" / f"{code}.json"
    if not p.exists():
        return {"thinker": code, "title": ""}
    m = json.loads(p.read_text(encoding="utf-8")).get("meta", {})
    return {"thinker": m.get("thinker", code), "title": m.get("title", "")}


def main():
    runs = gh_json(["run", "list", "--workflow=shorts.yml", "--status", "success",
                    "--limit", "200", "--json", "databaseId,url"])
    seen = {}  # code -> url (first/newest wins)
    for r in runs:
        rid = r["databaseId"]
        names = gh_lines(["api", f"repos/{{owner}}/{{repo}}/actions/runs/{rid}/artifacts",
                          "-q", '.artifacts[]|select(.name|startswith("short-"))|.name'])
        if not names:
            continue
        code = names[0].replace("short-", "")
        seen.setdefault(code, r["url"])

    codes = sorted(c for c in seen if c not in POSTED)
    lines = [
        "# ReadLark — new shorts to download & post",
        "",
        "Auto-generated by `tools/gen_shorts_links.py`. "
        "Open a link, then download the **`short-<CODE>`** artifact — that is the "
        "upload-ready vertical video plus title / description / hashtags.",
        "",
        "Already-posted shorts are excluded (see `POSTED` in the generator). "
        "Add a code there once you've published it.",
        "",
        "> GitHub keeps workflow artifacts ~30 days for shorts. Download before they expire.",
        "",
        f"**New shorts ready to post: {len(codes)}**",
        "",
        "| # | Thinker | Short | Code | Download (GitHub Actions run) |",
        "|---|---------|-------|------|-------------------------------|",
    ]
    for i, code in enumerate(codes, 1):
        m = meta_for(code)
        lines.append(f"| {i} | {m['thinker']} | {m['title']} | `{code}` | {seen[code]} |")
    lines.append("")

    (ROOT / "backlog" / "SHORTS_LINKS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote backlog/SHORTS_LINKS.md — {len(codes)} shorts")


if __name__ == "__main__":
    main()
